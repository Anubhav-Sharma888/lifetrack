package com.lifetrack.app.data

import java.util.Base64
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotEquals
import org.junit.Assert.assertThrows
import org.junit.Assert.assertTrue
import org.junit.Test

class BackupCryptoTest {
    private val password get() = "A private backup phrase 🌱".toCharArray()
    private val plain = """{"formatVersion":2,"name":"静かな時間 🌱","note":"A new beginning\nTomorrow too"}""".toByteArray()

    @Test fun `browser WebCrypto fixture decrypts identically in native backup utility`() {
        // Synthetic public interoperability vector generated by the actual preview WebCrypto module.
        val envelope = """{"kind":"lifetrack-encrypted","version":1,"kdf":"PBKDF2-HMAC-SHA256","iterations":600000,"salt":"55Xu5pL+QYEWpKuQmVKbuQ==","iv":"vgzNU/KA8R5VeaVs","ciphertext":"8IKyqgWFD3796XV+GYuVuQ8VoA9pyjgeNkSR3RIuKo4QX5Cy2LmhZSRXHAZ37eSSIG/dQuZ3QVuZylxGIkbCDfe/BwfwgBdBVMvtyU1UgJg="}""".toByteArray()
        val expected = Base64.getDecoder().decode("TGlmZVRyYWNrIGNyb3NzLXBsYXRmb3JtIGZpeHR1cmU6IOS5oOaDryDwn4yxIOCkqOCkruCkuOCljeCkpOClhw==")
        assertArrayEquals(expected, BackupCrypto.decrypt(envelope, "synthetic-test-password-26".toCharArray()))
    }

    private fun changed(bytes: ByteArray, field: String, value: JsonPrimitive): ByteArray {
        val fields = Json.parseToJsonElement(bytes.toString(Charsets.UTF_8)).jsonObject.toMutableMap()
        fields[field] = value
        return JsonObject(fields).toString().toByteArray(Charsets.UTF_8)
    }

    @Test fun `unicode backup round trips without changing caller password`() {
        val original = password
        val before = original.copyOf()
        val encrypted = BackupCrypto.encrypt(plain, original)
        assertTrue(BackupCrypto.isEncrypted(encrypted))
        assertArrayEquals(plain, BackupCrypto.decrypt(encrypted, original))
        assertArrayEquals(before, original)
        assertFalse(encrypted.toString(Charsets.UTF_8).contains("静かな時間"))
    }

    @Test fun `each export uses an independent salt iv and ciphertext`() {
        val first = BackupCrypto.encrypt(plain, password)
        val second = BackupCrypto.encrypt(plain, password)
        val a = Json.parseToJsonElement(first.toString(Charsets.UTF_8)).jsonObject
        val b = Json.parseToJsonElement(second.toString(Charsets.UTF_8)).jsonObject
        listOf("salt", "iv", "ciphertext").forEach { assertNotEquals(a[it], b[it]) }
        assertArrayEquals(plain, BackupCrypto.decrypt(first, password))
        assertArrayEquals(plain, BackupCrypto.decrypt(second, password))
    }

    @Test fun `wrong password cannot reveal plaintext`() {
        val encrypted = BackupCrypto.encrypt(plain, password)
        val failure = assertThrows(IllegalArgumentException::class.java) {
            BackupCrypto.decrypt(encrypted, "wrong but sufficiently long".toCharArray())
        }
        assertEquals("The password is incorrect or the backup has been changed or damaged.", failure.message)
    }

    @Test fun `ciphertext tampering is rejected by authenticated encryption`() {
        val encrypted = BackupCrypto.encrypt(plain, password)
        val root = Json.parseToJsonElement(encrypted.toString(Charsets.UTF_8)).jsonObject
        val payload = Base64.getDecoder().decode(root.getValue("ciphertext").jsonPrimitive.content)
        payload[payload.lastIndex] = (payload.last().toInt() xor 1).toByte()
        val modified = changed(encrypted, "ciphertext", JsonPrimitive(Base64.getEncoder().encodeToString(payload)))
        assertThrows(IllegalArgumentException::class.java) { BackupCrypto.decrypt(modified, password) }
    }

    @Test fun `interpretation metadata is authenticated even for allowed iteration values`() {
        val encrypted = BackupCrypto.encrypt(plain, password)
        val modified = changed(encrypted, "iterations", JsonPrimitive(BackupCrypto.ITERATIONS - 1))
        val failure = assertThrows(IllegalArgumentException::class.java) { BackupCrypto.decrypt(modified, password) }
        assertTrue(failure.message!!.contains("incorrect or the backup"))
    }

    @Test fun `salt and iv manipulation cannot bypass authentication`() {
        val encrypted = BackupCrypto.encrypt(plain, password)
        listOf("salt" to 16, "iv" to 12).forEach { (name, size) ->
            val changed = changed(encrypted, name, JsonPrimitive(Base64.getEncoder().encodeToString(ByteArray(size))))
            assertThrows(IllegalArgumentException::class.java) { BackupCrypto.decrypt(changed, password) }
        }
    }

    @Test fun `weak or excessive kdf parameters are rejected before derivation`() {
        val encrypted = BackupCrypto.encrypt(plain, password)
        listOf(-1, 1, 209_999, 600_001, Int.MAX_VALUE).forEach { rounds ->
            val modified = changed(encrypted, "iterations", JsonPrimitive(rounds))
            val failure = assertThrows(IllegalArgumentException::class.java) { BackupCrypto.decrypt(modified, password) }
            assertTrue(failure.message!!.contains("password-protection settings"))
        }
    }

    @Test fun `unknown format version or algorithm is rejected`() {
        val encrypted = BackupCrypto.encrypt(plain, password)
        listOf("version" to JsonPrimitive(2), "kdf" to JsonPrimitive("unknown"), "kind" to JsonPrimitive("another-app")).forEach { (key, value) ->
            val failure = assertThrows(IllegalArgumentException::class.java) { BackupCrypto.decrypt(changed(encrypted, key, value), password) }
            assertTrue(failure.message!!.contains("not supported"))
        }
    }

    @Test fun `short export passwords are rejected`() {
        assertThrows(IllegalArgumentException::class.java) { BackupCrypto.encrypt(plain, "too short".toCharArray()) }
        assertThrows(IllegalArgumentException::class.java) { BackupCrypto.encrypt(plain, CharArray(1_025) { 'a' }) }
    }

    @Test fun `plain and encrypted size bounds apply before expensive processing`() {
        assertThrows(IllegalArgumentException::class.java) { BackupCrypto.encrypt(ByteArray(BackupCrypto.MAX_PLAINTEXT_BYTES + 1), password) }
        assertThrows(IllegalArgumentException::class.java) { BackupCrypto.decrypt(ByteArray(BackupCrypto.MAX_ENVELOPE_BYTES + 1), password) }
        val encrypted = BackupCrypto.encrypt(plain, password)
        val oversized = changed(encrypted, "ciphertext", JsonPrimitive("A".repeat(((BackupCrypto.MAX_PLAINTEXT_BYTES + 18) / 3) * 4 + 4)))
        assertThrows(IllegalArgumentException::class.java) { BackupCrypto.decrypt(oversized, password) }
    }

    @Test fun `malformed encoding missing fields and json fail safely`() {
        val encrypted = BackupCrypto.encrypt(plain, password)
        val invalid = listOf(
            "not json".toByteArray(), "{}".toByteArray(),
            changed(encrypted, "salt", JsonPrimitive("!".repeat(24))),
            changed(encrypted, "iv", JsonPrimitive("A".repeat(12))),
            changed(encrypted, "ciphertext", JsonPrimitive("AAAA"))
        )
        invalid.forEach { assertThrows(IllegalArgumentException::class.java) { BackupCrypto.decrypt(it, password) } }
    }

    @Test fun `envelope recognition is explicit and accepts a utf8 bom`() {
        assertFalse(BackupCrypto.isEncrypted(plain))
        assertFalse(BackupCrypto.isEncrypted("not json".toByteArray()))
        assertFalse(BackupCrypto.isEncrypted("[]".toByteArray()))
        val encrypted = BackupCrypto.encrypt(plain, password)
        val withBom = byteArrayOf(0xEF.toByte(), 0xBB.toByte(), 0xBF.toByte()) + encrypted
        assertTrue(BackupCrypto.isEncrypted(withBom))
        assertArrayEquals(plain, BackupCrypto.decrypt(withBom, password))
    }
}
